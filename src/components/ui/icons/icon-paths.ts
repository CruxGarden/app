/**
 * Every UI glyph in three sets behind one name (ADR 0014, `iconSet` token).
 *
 *   line   — today's strokes on a 24px grid (fill none, round caps/joins)
 *   filled — solid silhouettes on the same 24px grid and metrics
 *   pixel  — 16px-grid pixel art: integer coordinates only, drawn crisp
 *
 * All three are plain SVG `d` strings so a test can check the whole set.
 * Pixel glyphs are drawn as 16 rows of 16 characters (`#` = lit) and turned
 * into unit-square runs by px(); nothing here has a dependency.
 */

// ── path helpers ─────────────────────────────────────────

const circ = (cx: number, cy: number, r: number) =>
  `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0z`;
const ellipse = (cx: number, cy: number, rx: number, ry: number) =>
  `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0z`;
const rect = (x: number, y: number, w: number, h: number, r = 0) =>
  r === 0
    ? `M${x} ${y}h${w}v${h}h${-w}z`
    : `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}z`;
const line = (x1: number, y1: number, x2: number, y2: number) => `M${x1} ${y1}L${x2} ${y2}`;

/** 16×16 ASCII art → one path of horizontal unit runs (integer coordinates only). */
export function px(rows: readonly string[]): string {
  if (rows.length !== 16) throw new Error(`pixel glyph needs 16 rows, got ${rows.length}`);
  const out: string[] = [];
  rows.forEach((row, y) => {
    if (row.length !== 16) throw new Error(`pixel row ${y} needs 16 columns: "${row}"`);
    let x = 0;
    while (x < 16) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      let w = 0;
      while (row[x + w] === '#') w++;
      out.push(`M${x} ${y}h${w}v1h${-w}z`);
      x += w;
    }
  });
  return out.join('');
}

