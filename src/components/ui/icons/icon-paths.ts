export interface Glyph {
  /** Stroke path, 24 grid. */
  line: string;
  /** Default stroke width for the line set (callers may override). */
  strokeWidth?: number;
  /** Line glyphs that were always solid (transport controls). */
  lineFill?: boolean;
  /** Solid path, 24 grid. */
  filled: string;
  /** Fill rule for the filled path: evenodd when holes are cut, nonzero to union shapes. */
  filledRule?: 'evenodd' | 'nonzero';
  /** Pixel path, 16 grid. */
  pixel: string;
}

