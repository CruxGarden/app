/** The same body/frame/header for every pane (uniform looks). */
function uniformPanes(t: {
  body: string;
  surface?: string;
  border: string;
  header: string;
  headerText: string;
  headerBorder?: string;
  text?: string;
  textMuted?: string;
  caption?: string;
  heading?: string;
  accent?: string;
  radius?: string;
  headerRadius?: string;
  headerHeight?: string;
  borderWidth?: string;
}) {
  const result: Record<string, string> = {};
  for (const key of ALL_PANES) {
    result[`${key}Body`] = t.body;
    if (t.surface) result[`${key}Surface`] = t.surface;
    result[`${key}Border`] = t.border;
    result[`${key}Header`] = t.header;
    result[`${key}HeaderBorder`] = t.headerBorder ?? 'transparent';
    result[`${key}HeaderText`] = t.headerText;
    result[`${key}HeaderIcon`] = t.headerText;
    result[`${key}HeaderClose`] = t.headerText;
    if (t.text) result[`${key}Text`] = t.text;
    if (t.textMuted) result[`${key}TextMuted`] = t.textMuted;
    if (t.caption) result[`${key}Caption`] = t.caption;
    if (t.heading) result[`${key}Heading`] = t.heading;
    if (t.accent) result[`${key}Accent`] = t.accent;
    if (t.radius) result[`${key}Radius`] = t.radius;
    if (t.headerRadius) result[`${key}HeaderRadius`] = t.headerRadius;
    if (t.headerHeight) result[`${key}HeaderHeight`] = t.headerHeight;
    if (t.borderWidth) result[`${key}BorderWidth`] = t.borderWidth;
  }
  return result;
}

/** Each pane its own header tint from a list (pastel looks). */
function tintedHeaders(tints: string[], text: string) {
  const result: Record<string, string> = {};
  ALL_PANES.forEach((key, i) => {
    const tint = tints[i % tints.length]!;
    result[key] = tint;
    result[`${key}Header`] = tint;
    result[`${key}HeaderBorder`] = 'transparent';
    result[`${key}HeaderText`] = text;
    result[`${key}HeaderIcon`] = text;
    result[`${key}HeaderClose`] = text;
    result[`${key}Caption`] = tint;
    result[`${key}ButtonIcon`] = tint;
    result[`${key}ButtonActive`] = `color-mix(in srgb, ${tint} 25%, transparent)`;
  });
  return result;
}

